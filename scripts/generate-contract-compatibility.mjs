#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTRACT_COMPATIBILITY } from '../cli/lib/contract-compatibility.mjs';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDirectory, '..');
const outputPath = join(root, 'workflow', 'Contract-Compatibility.md');

function compatibilityText(contract) {
  if (contract.compatibility.length === 0) return 'Independent transport contract; runtime compatibility follows the exact pinned toolkit/CLI revision.';
  return contract.compatibility
    .map((item) => `${item.contract} ${item.versions.map((version) => `v${version}`).join('/')} (${item.mode})`)
    .join('; ');
}

export function renderContractCompatibilityMarkdown() {
  const rows = CONTRACT_COMPATIBILITY.map((contract) => (
    `| ${contract.label} | ${contract.kind} | v${contract.currentVersion} | ${compatibilityText(contract)} | \`${contract.owner}\` |`
  ));

  const notes = CONTRACT_COMPATIBILITY.flatMap((contract) => (
    contract.notes.map((note) => `- **${contract.label}:** ${note}`)
  ));

  return `${[
    '# Contract Compatibility',
    '',
    '> Generated from `cli/lib/contract-compatibility.mjs`. Do not edit this file manually.',
    '',
    'The toolkit versions independent external contracts separately. There is intentionally no global workflow protocol version, and equal version numbers across contracts do not imply coupled compatibility or synchronized release cadence.',
    '',
    '| Contract | Kind | Current | Compatibility | Runtime owner |',
    '|---|---|---:|---|---|',
    ...rows,
    '',
    '## Contract notes',
    '',
    ...notes,
    '',
    '## Version-bump procedure',
    '',
    '1. Change only the contract whose externally observable shape or semantics changed.',
    '2. Update `cli/lib/contract-compatibility.mjs` first, including compatibility relationships and migration-only behavior.',
    '3. Update the affected producer/consumer implementation and focused regression tests.',
    '4. Run `node scripts/generate-contract-compatibility.mjs` to refresh this table.',
    '5. Run `npm run validate` before merging.',
    '',
    'Do not bump unrelated contracts merely to keep version numbers visually aligned.',
    '',
  ].join('\n')}`;
}

const rendered = renderContractCompatibilityMarkdown();

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {
    // Report the same actionable drift error for missing and stale generated output.
  }
  if (current !== rendered) {
    process.stderr.write('workflow/Contract-Compatibility.md is stale. Run node scripts/generate-contract-compatibility.mjs.\n');
    process.exitCode = 1;
  } else {
    process.stdout.write('Contract compatibility documentation is current.\n');
  }
} else {
  writeFileSync(outputPath, rendered, 'utf8');
  process.stdout.write('Updated workflow/Contract-Compatibility.md.\n');
}
